local function sine(direction)
    direction = direction % 512
    local half = direction % 256
    local value = quarter[math.min(half,256-half)+1]
    return direction < 256 and value or -value
end

-- 0x0c0632b0 先截掉定点差值的小数位，再查短距离表或搜索向量表。
local function heading(x, y, targetX, targetY)
    local dx, dy = floor((targetX-x)/unit), floor((targetY-y)/unit)
    local ax, ay = abs(dx), abs(dy)
    local direction
    if ax == ay then
        direction = 64
    elseif ax == 0 then direction = 0
    elseif ay == 0 then direction = 128
    elseif ax <= 32 and ay <= 32 then
        direction = near:byte((ay-1)*33+ax+1)
    elseif ay > ax then
        direction = 0
        while direction < 64 and floor(sine(direction)/32)*ay < -floor(sine(384+direction)/32)*ax do
            direction = direction + 1
        end
    else
        direction = 128
        while direction > 64 and -floor(sine(384+direction)/32)*ax < floor(sine(direction)/32)*ay do
            direction = direction - 1
        end
    end
    if dy < 0 then direction = 256-direction end
    if dx < 0 then direction = -direction end
    return direction % 512
end

